/**
 * Данные графика «Своя лаборатория — своя цена».
 *
 * Сами числа и подписи лежат в price-chart.json — их правит владелец в
 * редакторе сайта (Главная страница → «7. Почему мы — график цен»). Здесь
 * только типы и то, что из них считается.
 *
 * РЫНОК. Ряд взят из вашего анализа рынка (артефакт «Динамика цены E-max»,
 * коронка E-max «под ключ», Москва, 2026) — в редакции по эконом- и среднему
 * сегменту: премиум-клиники (60 000–87 000 ₽) в расчёт не входят, взят
 * массовый сегмент 20 000–40 000 ₽.
 *
 * У рынка стоматологии нет открытого архива цен по месяцам: клиники и
 * агрегаторы публикуют только текущий прайс. Реально измеренная точка одна —
 * сентябрь 2026 (30 000 ₽, середина диапазона по открытым прайсам). Остальные
 * месяцы — расчёт по данным Росстата об индексе цен на стоматологические
 * услуги, октябрь–декабрь — прогноз. Рост за год +6,6%, поэтому кривая рынка
 * поднимается полого: это настоящая динамика, а не сглаживание.
 *
 * НАША ЦЕНА. Начинали год с 25 000 ₽ за коронку, в течение года снижали,
 * к концу лета вышли на акционные 19 900 ₽ за циркониевую коронку.
 * Помесячные значения между этими точками — ориентир, а не бухгалтерская
 * выгрузка: если в клинике есть точные даты изменения прайса, их можно
 * поправить в редакторе, вёрстку трогать не нужно.
 *
 * Ряды сопоставляют цену коронки в клинике со средней ценой коронки по
 * рынку. Материалы разные (у рынка это E-max, у нас к сентябрю цирконий
 * по акции) — об этом сказано в сноске под графиком.
 */
import raw from './price-chart.json';

export type PriceChartPoint = {
  month: string;
  market: number;
  clinic: number;
  /** true — прогноз рынка, а не расчёт от факта */
  forecast: boolean;
  /** true — месяц, с которого действует акция: крупная точка на линии */
  promo?: boolean;
};

export const priceChart: {
  title: string;
  marketLabel: string;
  clinicLabel: string;
  /** Год рядов — в подсказке над точкой («Сен 2026») */
  year: string;
  /** Месяц, по которому считается разница под графиком */
  anchorMonth: string;
  note: string;
  data: PriceChartPoint[];
} = raw;

